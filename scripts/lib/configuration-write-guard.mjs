import { existsSync, lstatSync, readFileSync, readlinkSync, realpathSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { isDeepStrictEqual } from "node:util";

const manifest = process.env.HARNESS_CONFIGURATION_WRITE_GUARD
	? JSON.parse(readFileSync(process.env.HARNESS_CONFIGURATION_WRITE_GUARD, "utf8")) : null;

function state(path) {
	try {
		const stat = lstatSync(path);
		if (stat.isSymbolicLink()) return { type: "symlink", value: readlinkSync(path) };
		if (stat.isFile()) return { type: "file", content: readFileSync(path).toString("base64"), mode: stat.mode & 0o777 };
		return { type: "entity" };
	} catch (error) { if (error.code === "ENOENT") return { type: "missing" }; throw error; }
}

/** Internal sync child-process guard: recheck exact approved destination and parents at write time.
 * The private manifest is generated by the trusted controller, never accepted from HTTP or Catalog.
 * It complements the cooperative Catalog lock; it is not a cross-file filesystem transaction.
 */
export function assertConfigurationWrite(path, root) {
	const suffix = relative(root, path);
	if (suffix.startsWith("../") || suffix === "..") throw new Error("Configuration write target is outside its declared root.");
	let ancestor = root;
	while (!existsSync(ancestor)) ancestor = dirname(ancestor);
	root = join(realpathSync(ancestor), relative(ancestor, root));
	let parent = dirname(join(root, suffix));
	while (parent !== root) {
		if (!parent.startsWith(`${root}/`) || (existsSync(parent) && realpathSync(parent) !== parent)) throw new Error("Configuration write parent changed or is a symlink; stopped.");
		parent = dirname(parent);
	}
	if (manifest && (!Object.hasOwn(manifest.expected, path) || !isDeepStrictEqual(state(path), manifest.expected[path]))) {
		throw Object.assign(new Error("Configuration destination changed; stopped without overwriting it."), { code: "ECHANGED" });
	}
}
